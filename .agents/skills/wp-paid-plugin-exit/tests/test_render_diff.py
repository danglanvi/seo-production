#!/usr/bin/env python3
"""Test offline cho scripts/render_diff.py. Chạy: python3 -B tests/test_render_diff.py"""
import json, os, sys, tempfile, unittest

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'scripts'))
import render_diff  # noqa: E402

HP = ('<style>#wpforms-5-field_{n}-container{{position: absolute !important;}}</style>'
      '<form><div id="wpforms-5-field_{n}-container" class="wpforms-field"><label>{nhan}</label><input name="x"></div>'
      '<input type="hidden" name="_wpnonce" value="{nonce}"></form>')


def page(body, n=7, nhan='Abc', nonce='a1b2c3d4e5'):
    return f'<html><head><link rel="canonical" href="https://site.vn/a/"></head><body><h1>{body}</h1>{HP.format(n=n, nhan=nhan, nonce=nonce)}<!-- Page generated by LiteSpeed Cache 6.5 on 2026-10-24 08:00:01 --></body></html>'


def snap(root, name, pages, status=200):
    d = os.path.join(root, name)
    os.makedirs(d)
    idx = []
    for i, html in enumerate(pages):
        open(os.path.join(d, '%04d.html' % i), 'w', encoding='utf-8').write(html)
        idx.append({'i': i, 'url': f'/p{i}/', 'status': status, 'loc': ''})
    json.dump(idx, open(os.path.join(d, 'index.json'), 'w'))
    return d


class RenderDiff(unittest.TestCase):
    def setUp(self):
        self.t = tempfile.TemporaryDirectory()

    def tearDown(self):
        self.t.cleanup()

    def test_honeypot_nonce_gio_khong_tinh_la_khac(self):
        # Lỗi thật 24/10/2026: nhãn và id honeypot WPForms đổi mỗi lượt, 11/352 URL báo khác.
        b1 = snap(self.t.name, 'b1', [page('Dịch vụ SEO', n=7, nhan='Xyz', nonce='1111aaaa22')])
        b2 = snap(self.t.name, 'b2', [page('Dịch vụ SEO', n=9, nhan='Qwe', nonce='3333bbbb44')])
        a = snap(self.t.name, 'a', [page('Dịch vụ SEO', n=4, nhan='Mno', nonce='5555cccc66')])
        r = render_diff.compare([b1, b2], a)
        self.assertEqual(r['real_diff'], [])
        self.assertEqual(r['full_same'] + r['content_same'] + len(r['noise_only']), 1)

    def test_chu_doi_that(self):
        b1 = snap(self.t.name, 'b1', [page('Dịch vụ SEO')])
        b2 = snap(self.t.name, 'b2', [page('Dịch vụ SEO')])
        a = snap(self.t.name, 'a', [page('Dịch vụ GEO')])
        r = render_diff.compare([b1, b2], a)
        self.assertEqual(r['real_diff'], ['/p0/'])
        self.assertIn('T Dịch vụ GEO', r['detail']['/p0/']['added'])

    def test_dong_doi_giua_2_ban_truoc_la_nhieu(self):
        b1 = snap(self.t.name, 'b1', [page('A') + '<p>Bài mới: X</p>'])
        b2 = snap(self.t.name, 'b2', [page('A') + '<p>Bài mới: Y</p>'])
        a = snap(self.t.name, 'a', [page('A') + '<p>Bài mới: X</p><p>Bài mới: Y</p>'])
        r = render_diff.compare([b1, b2], a)
        self.assertEqual(r['real_diff'], [])

    def test_khac_ma_http(self):
        b1 = snap(self.t.name, 'b1', [page('A')])
        b2 = snap(self.t.name, 'b2', [page('A')])
        a = snap(self.t.name, 'a', [page('A')], status=500)
        r = render_diff.compare([b1, b2], a)
        self.assertEqual(r['status_diff'], [['/p0/', [200, 200], 500]])


if __name__ == '__main__':
    unittest.main()
